export function getQuestion(id: number): QuestQuestion | undefined {
  return questions.find((item) => item.id === id)
}

export function getChapter(questionNumber: number): QuestChapter {
  return chapters.find(({ start, end }) => questionNumber >= start && questionNumber <= end) ?? chapters[0]!
}

export function getChoiceText(questionData: QuestQuestion, choiceId: ChoiceId): string {
  return questionData.options.find(({ id }) => id === choiceId)?.text ?? 'Выбор не сохранился'
}
